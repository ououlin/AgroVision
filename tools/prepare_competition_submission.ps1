[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('graduate', 'undergraduate')]
    [string]$Track,

    [Parameter(Mandatory = $true)]
    [ValidatePattern('^\d+$')]
    [string]$EntryNumber,

    [string]$OutputRoot = (Join-Path $PSScriptRoot '..\competition\out'),

    [switch]$CreateZip
)

$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$output = (Resolve-Path $OutputRoot -ErrorAction SilentlyContinue)
if ($null -eq $output) {
    New-Item -ItemType Directory -Force -Path $OutputRoot | Out-Null
    $output = (Resolve-Path $OutputRoot).Path
} else {
    $output = $output.Path
}

$trackName = if ($Track -eq 'graduate') {
    [string]::Concat([char[]]@(0x7814, 0x7A76, 0x751F, 0x7EC4))
} else {
    [string]::Concat([char[]]@(0x672C, 0x79D1, 0x9AD8, 0x804C, 0x7EC4))
}
$packageName = $trackName + $EntryNumber + 'submission'
$staging = Join-Path $output $packageName
if (Test-Path $staging) {
    throw "Target already exists. Choose another OutputRoot: $staging"
}
New-Item -ItemType Directory -Force -Path $staging | Out-Null

function Copy-RepoTree {
    param([string]$RelativePath)

    $source = Join-Path $repo $RelativePath
    if (-not (Test-Path $source)) {
        throw "Repository path does not exist: $RelativePath"
    }

    $destination = Join-Path $staging $RelativePath
    New-Item -ItemType Directory -Force -Path $destination | Out-Null
    & robocopy $source $destination /E /NFL /NDL /NJH /NJS /NP `
        /XD '.gradle' 'build' 'out' 'output' 'captures' 'plant_dataset' `
        /XF 'local.properties' '*.jks' '*.keystore' '*.p12' '*.pem' '*.key' '*.log' | Out-Null
    if ($LASTEXITCODE -gt 7) {
        throw "Failed to copy $RelativePath. robocopy=$LASTEXITCODE"
    }
}

foreach ($tree in @('app', 'backend', 'docs', 'gradle', 'tools', 'competition')) {
    Copy-RepoTree $tree
}

foreach ($file in @(
    '.gitignore',
    'build.gradle.kts',
    'gradle.properties',
    'gradlew',
    'gradlew.bat',
    'settings.gradle.kts',
    'README.md',
    'V2.0.md'
)) {
    $source = Join-Path $repo $file
    if (Test-Path $source) {
        $destination = Join-Path $staging $file
        New-Item -ItemType Directory -Force -Path (Split-Path $destination) | Out-Null
        Copy-Item $source $destination
    }
}

$datasetDir = Join-Path $staging 'competition\02_data\datasets'
New-Item -ItemType Directory -Force -Path $datasetDir | Out-Null

$firstRead = @(
    "# $packageName",
    '',
    'Generated by tools/prepare_competition_submission.ps1.',
    '',
    '## Manual checks required before submission',
    '',
    '- Add the licensed dataset under competition/02_data/datasets and update the manifest.',
    '- Add the final model and model card under competition/03_model/.',
    '- Add the final PDF test report under competition/04_testing/.',
    '- Add the final two-minute video under competition/05_demo/.',
    '- Complete competition/06_submission/MATERIAL_CHECKLIST.md.',
    '- Verify that no local configuration, secrets, caches, or stale APKs are included.',
    '',
    '## Environment',
    '',
    'See competition/01_project/ENVIRONMENT.md.'
) -join [Environment]::NewLine
Set-Content -LiteralPath (Join-Path $staging 'README_FIRST.md') -Value $firstRead -Encoding UTF8

$hashFile = Join-Path $staging 'SHA256SUMS.txt'
Get-ChildItem $staging -File -Recurse | Sort-Object FullName | ForEach-Object {
    $hash = Get-FileHash $_.FullName -Algorithm SHA256
    $relative = $_.FullName.Substring($staging.Length + 1)
    "$($hash.Hash)  $relative"
} | Set-Content -LiteralPath $hashFile -Encoding ASCII

if ($CreateZip) {
    $zip = Join-Path $output "$packageName.zip"
    Compress-Archive -Path $staging -DestinationPath $zip -CompressionLevel Optimal
    Write-Output "ZIP=$zip"
    Write-Output "ZIP_SHA256=$((Get-FileHash $zip -Algorithm SHA256).Hash)"
}

Write-Output "STAGING=$staging"
Write-Output "FILE_COUNT=$((Get-ChildItem $staging -File -Recurse).Count)"
Write-Output "TOTAL_BYTES=$((Get-ChildItem $staging -File -Recurse | Measure-Object Length -Sum).Sum)"
Write-Output "NEXT=Complete competition/06_submission/MATERIAL_CHECKLIST.md before sending."
